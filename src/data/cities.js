// In production these would come from a places API + Google Popular Times.

// Helper: build a crowd-by-hour curve. All curves are 24 ints (0..23).
// peak = array of hours that hit the max; quietest = the trough hours.
function curve({ quiet, normal, peak }) {
  const arr = Array(24).fill(normal)
  for (const h of quiet) arr[h] = 0
  for (const h of peak) arr[h] = Math.max(2, peak.length ? 4 : 0)
  return arr
}

